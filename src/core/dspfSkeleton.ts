// An RPG program skeleton for a display file: the WORKSTN file with an indicator data structure, the function keys it
// defines, a loop for each record format and, for a subfile, clear / load / display procedures. Pure, unit tested.

import { Dspf } from './dspf';

export interface FunctionKey { key: string; indicator: string; text: string; kind: 'CA' | 'CF' }

/** CA03(03 'Exit') / CF05(05) keywords of the file and of a record. */
export function functionKeys(keywords: string): FunctionKey[] {
  const out: FunctionKey[] = [];
  for (const m of keywords.matchAll(/\b(CA|CF)(\d{2})(?:\s*\(\s*(\d{2})?\s*(?:'([^']*)')?\s*\))?/gi)) {
    out.push({ kind: m[1].toUpperCase() as 'CA' | 'CF', key: `F${Number(m[2])}`, indicator: m[3] ?? '', text: m[4] ?? '' });
  }
  return out;
}

const ident = (s: string) => s.toLowerCase().replace(/[^a-z0-9_]/g, '_');

/** Indicator conditioning a keyword (SFLDSP, SFLCLR, SFLEND…) of a record: columns 8-16 of the DDS line (N-prefixed ones skipped). */
function indicatorFor(source: string[], d: Dspf, record: string, keyword: string): string | undefined {
  const r = d.records.find(x => x.name === record);
  if (!r) { return undefined; }
  const next = d.records.filter(x => x.srcLine > r.srcLine).map(x => x.srcLine).sort((a, b) => a - b)[0] ?? source.length;
  for (let i = r.srcLine; i < next; i++) {
    const l = (source[i] ?? '').padEnd(80);
    if (l[6] === '*' || !new RegExp(`\\b${keyword}\\b`, 'i').test(l.substring(44))) { continue; }
    const conds = l.substring(7, 16).match(/N?\d{2}/gi) ?? [];
    return conds.find(c => !/^N/i.test(c));
  }
  return undefined;
}

export function rpgForDspf(file: string, d: Dspf, source = ''): string {
  const src = source.split(/\r?\n/);
  const name = file.toUpperCase();
  const keys = [...functionKeys(d.fileKeywords), ...d.records.flatMap(r => functionKeys(r.keywords))];
  const uniq = [...new Map(keys.map(k => [k.key, k])).values()];
  const sfl = d.records.filter(r => r.sfl);
  const ctls = d.records.filter(r => r.sflctl);
  const plain = d.records.filter(r => !r.sfl && !r.sflctl);
  const usesIndara = /\bINDARA\b/i.test(d.fileKeywords);
  const ind = (n: string) => (usesIndara ? `ind.in${n}` : `*in${n}`);
  const lines: string[] = [
    '**FREE',
    `// Generated by Vanthrex for IBM i from ${name}. A starting point: fill in the parts marked TODO.`,
    "ctl-opt dftactgrp(*no) actgrp(*caller) option(*srcstmt: *nodebugio);",
    '',
    `dcl-f ${ident(name)} workstn${sfl.length ? `${sfl.map(s => ` sfile(${s.name}: rrn_${ident(s.name)})`).join('')}` : ''}${usesIndara ? ' indds(ind)' : ''};`,
  ];
  if (usesIndara) {
    lines.push('', '// Indicators of the display file (INDARA).', 'dcl-ds ind qualified;');
    for (let i = 1; i <= 99; i++) {
      const n = String(i).padStart(2, '0');
      const k = uniq.find(x => x.indicator === n);
      const used = k || d.records.some(r => new RegExp(`\\b${n}\\b`).test(r.keywords + r.fields.map(f => f.indicators ?? '').join(' ')));
      if (used) { lines.push(`  in${n} ind pos(${i});${k ? ` // ${k.key}${k.text ? ' ' + k.text : ''}` : ''}`); }
    }
    lines.push('end-ds;');
  }
  for (const s of sfl) { lines.push(`dcl-s rrn_${ident(s.name)} packed(4: 0); // relative record number of subfile ${s.name}`); }
  lines.push('dcl-s done ind;', '');
  const exitKey = uniq.find(k => k.key === 'F3') ?? uniq.find(k => k.key === 'F12');
  const keyCheck = (k: FunctionKey) => (k.indicator ? ind(k.indicator) : `*in${k.key.slice(1).padStart(2, '0')} // TODO: ${k.kind}${k.key.slice(1).padStart(2, '0')} has no response indicator — use the AID byte (INFDS position 369)`);
  const screen = ctls[0] ?? plain[0];
  lines.push('// ---- main loop ----', 'dou done;');
  if (ctls.length) { for (const c of ctls) { lines.push(`  load${ident(c.sflctl!)}();`); } }
  if (screen) {
    for (const p of plain.filter(r => r !== screen && !r.overlay && /\bOVERLAY\b/i.test(screen.keywords))) { lines.push(`  write ${p.name}; // TODO: keep only the formats shown together`); }
    lines.push(`  exfmt ${screen.name};`);
  }
  for (const k of uniq) {
    const isExit = k === exitKey || k.key === 'F3' || k.key === 'F12';
    lines.push(`  if ${keyCheck(k)}; // ${k.key}${k.text ? ' ' + k.text : ''}`, isExit ? '    done = *on;' : `    // TODO: what ${k.key} does`, '    iter;', '  endif;');
  }
  if (ctls.length) { for (const c of ctls) { lines.push(`  process${ident(c.sflctl!)}();`); } }
  else { lines.push('  // TODO: validate the input and do the work'); }
  lines.push('enddo;', '*inlr = *on;', 'return;', '');
  for (const c of ctls) {
    const s = c.sflctl!; const id = ident(s);
    const clr = indicatorFor(src, d, c.name, 'SFLCLR'); const dsp = indicatorFor(src, d, c.name, 'SFLDSP'); const end = indicatorFor(src, d, c.name, 'SFLEND');
    const sflRec = d.records.find(r => r.name === s);
    const inputs = sflRec?.fields.filter(f => f.kind === 'field' && (f.usage === 'I' || f.usage === 'B')) ?? [];
    const assigns = (sflRec?.fields ?? []).filter(f => f.kind === 'field' && f.usage !== 'H').map(f => f.name + ' = …;').slice(0, 6).join(' ');
    lines.push(
      `// ---- subfile ${s} (control record ${c.name}) ----`,
      `dcl-proc load${id};`,
      `  rrn_${id} = 0;`,
      clr ? `  ${ind(clr)} = *on;  // SFLCLR` : '  // TODO: no SFLCLR indicator found — clear the subfile here',
      `  write ${c.name};`,
      clr ? `  ${ind(clr)} = *off;` : '',
      '  // TODO: read the rows (an SQL cursor or a READ loop) and for each one:',
      '  //   ' + (assigns || 'set the fields'),
      `  //   rrn_${id} += 1;`,
      `  //   write ${s};`,
      dsp ? `  ${ind(dsp)} = (rrn_${id} > 0); // SFLDSP: show the subfile only when it has rows` : '  // TODO: set the SFLDSP indicator when rrn > 0',
      end ? `  ${ind(end)} = *on;  // SFLEND: all rows loaded` : '',
      'end-proc;',
      '',
      `dcl-proc process${id};`,
      inputs.length ? `  // Read back the changed rows (input fields: ${inputs.map(f => f.name).join(', ')}).` : '  // The subfile has no input fields: nothing to read back.',
      ...(inputs.length ? [`  readc ${s};`, `  dow not %eof(${ident(name)});`, '    // TODO: act on the option / changed fields of this row', `    readc ${s};`, '  enddo;'] : []),
      'end-proc;',
      '',
    );
  }
  return lines.filter((l, i, a) => !(l === '' && a[i - 1] === '')).join('\n');
}
