// IBM i Project (Bob / IBM i Project Explorer / makei) files for a local source folder: iproj.json, .ibmi.json and
// Rules.mk with a target for each source and its /COPY dependencies. Pure (no vscode import), unit tested.

export interface ProjectFile { rel: string; text?: string }
export interface Target { dir: string; target: string; source: string; deps: string[] }

const INCLUDE = /\.(rpgleinc|rpginc|clinc|sqlinc|cblinc|inc|h)$/i;

/** The object a source builds, by Bob's naming: name.pgm.rpgle → NAME.PGM, name.rpgle → NAME.MODULE, name.pf → NAME.FILE… */
export function targetOf(file: string): string | undefined {
  const base = file.split('/').pop() ?? file;
  const parts = base.split('.');
  if (parts.length < 2 || INCLUDE.test(base)) { return undefined; }
  const ext = parts[parts.length - 1].toLowerCase();
  const kind = parts.length >= 3 ? parts[parts.length - 2].toLowerCase() : '';
  const name = parts[0].toUpperCase().replace(/[^A-Z0-9$#@_]/g, '').slice(0, 10);
  if (!name) { return undefined; }
  if (kind === 'pgm' && /^(rpgle|sqlrpgle|clle|cblle|sqlcblle|c|cpp)$/.test(ext)) { return `${name}.PGM`; }
  if (kind === 'srvpgm' || ext === 'bnd') { return `${name}.SRVPGM`; }
  if (/^(rpgle|sqlrpgle|clle|cblle|sqlcblle|c|cpp)$/.test(ext)) { return `${name}.MODULE`; }
  if (/^(pf|lf|dspf|prtf|table|view|index)$/.test(ext)) { return `${name}.FILE`; }
  if (ext === 'cmd') { return `${name}.CMD`; }
  if (ext === 'msgf') { return `${name}.MSGF`; }
  if (ext === 'dtaara') { return `${name}.DTAARA`; }
  if (ext === 'sqlprc') { return `${name}.PGM`; }
  if (ext === 'sqludf' || ext === 'sqludt') { return `${name}.SRVPGM`; }
  if (ext === 'sql' || ext === 'sqlseq' || ext === 'sqltrg') { return `${name}.FILE`; }
  if (ext === 'bnddir') { return `${name}.BNDDIR`; }
  return undefined;
}

/** /COPY and /INCLUDE targets of a source (the member or file name, upper case). */
export function copiesIn(text: string): string[] {
  const out = new Set<string>();
  for (const m of text.matchAll(/^(?:.{5}[ A-Za-z]|\s*)\/(?:copy|include)\s+['"]?([^'"\s]+)['"]?/gim)) {
    const t = m[1].replace(/\\/g, '/');
    const name = (t.includes('/') && !t.includes(',') ? t.split('/').pop()! : t.split(',').pop()!).replace(/\.[^.]*$/, '');
    out.add(name.toUpperCase());
  }
  return [...out];
}

export function projectTargets(files: ProjectFile[]): Target[] {
  const includes = new Map<string, string>();
  for (const f of files) {
    const base = (f.rel.split('/').pop() ?? '').replace(/\.[^.]*$/, '').replace(/\.[^.]*$/, '').toUpperCase();
    if (INCLUDE.test(f.rel)) { includes.set(base, f.rel); }
  }
  const out: Target[] = [];
  for (const f of files) {
    const target = targetOf(f.rel);
    if (!target) { continue; }
    const dir = f.rel.includes('/') ? f.rel.slice(0, f.rel.lastIndexOf('/')) : '';
    const deps = copiesIn(f.text ?? '').map(c => includes.get(c)).filter((x): x is string => !!x);
    out.push({ dir, target, source: f.rel.slice(dir ? dir.length + 1 : 0), deps });
  }
  return out.sort((a, b) => a.dir.localeCompare(b.dir) || a.target.localeCompare(b.target));
}

const relTo = (fromDir: string, file: string) => {
  const a = fromDir ? fromDir.split('/') : []; const b = file.split('/');
  let i = 0; while (i < a.length && i < b.length - 1 && a[i] === b[i]) { i++; }
  return [...Array(a.length - i).fill('..'), ...b.slice(i)].join('/');
};

/** Rules.mk of one folder. */
export function rulesMk(dir: string, targets: Target[]): string {
  const mine = targets.filter(t => t.dir === dir);
  const lines = ['# Generated by Vanthrex for IBM i — one rule per object: TARGET: source [dependencies]', ''];
  for (const t of mine) { lines.push(`${t.target}: ${[t.source, ...t.deps.map(d => relTo(dir, d))].join(' ')}`); }
  return lines.join('\n') + '\n';
}

export interface ProjectOptions { name: string; description?: string; curlib?: string; objlib?: string; libl?: string[]; tgtCcsid?: number }

export function iprojJson(o: ProjectOptions, includeDirs: string[]): string {
  return JSON.stringify({
    description: o.description || o.name,
    version: '1.0.0',
    license: '',
    repository: '',
    includePath: includeDirs,
    objlib: o.objlib || '&CURLIB',
    curlib: o.curlib || '&CURLIB',
    preUsrlibl: o.libl ?? [],
    postUsrlibl: [],
    setIBMiEnvCmd: [],
    buildCommand: 'makei build',
    compileCommand: 'makei compile -f {filename}',
  }, null, 2) + '\n';
}

export function ibmiJson(o: ProjectOptions): string {
  return JSON.stringify({ version: '0.0.1', build: { objlib: o.objlib || '&CURLIB', tgtCcsid: o.tgtCcsid ?? '*JOB' } }, null, 2) + '\n';
}

/** Folders that hold include (copybook) files, for iproj.json includePath. */
export function includeDirs(files: ProjectFile[]): string[] {
  return [...new Set(files.filter(f => INCLUDE.test(f.rel)).map(f => (f.rel.includes('/') ? f.rel.slice(0, f.rel.lastIndexOf('/')) : '.')))].sort();
}
