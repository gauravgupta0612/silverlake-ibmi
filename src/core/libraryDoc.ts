// Library documentation (Markdown with a Mermaid diagram) and the CRUD matrix (which program creates, reads, updates
// or deletes which file), from object lists, columns and DSPPGMREF references. Pure (no vscode import), unit tested.

import { PgmRef } from './callGraph';

export interface DocObject { name: string; type: string; attribute: string; text: string; size?: number; lastUsed?: string; created?: string }
export interface DocColumn { file: string; name: string; type: string; length: number; scale: number; text: string }

/** C / R / U / D letters of DSPPGMREF file usage bits (1 input, 2 output, 4 update/delete, 8 unspecified). */
export function crud(usage: number | undefined): string {
  const u = usage ?? 0;
  if (!u) { return ''; }
  if (u & 8) { return '?'; }
  return `${u & 2 ? 'C' : ''}${u & 1 ? 'R' : ''}${u & 4 ? 'UD' : ''}`;
}

export interface CrudMatrix { programs: string[]; files: string[]; cells: Record<string, Record<string, string>> }

/** Programs (rows) × files (columns); a file used by several modules of a program merges its letters. */
export function crudMatrix(refs: PgmRef[]): CrudMatrix {
  const cells: Record<string, Record<string, string>> = {};
  const files = new Set<string>();
  for (const r of refs.filter(x => x.refType.toUpperCase() === '*FILE' && x.refName)) {
    const p = `${r.lib}/${r.pgm}`; const f = `${r.refLib && !r.refLib.startsWith('*') ? r.refLib + '/' : ''}${r.refName}`;
    files.add(f);
    const prev = (cells[p] ??= {})[f] ?? '';
    const merged = [...new Set((prev + crud(r.usage)).split(''))];
    cells[p][f] = ['C', 'R', 'U', 'D', '?'].filter(l => merged.includes(l)).join('');
  }
  return { programs: Object.keys(cells).sort(), files: [...files].sort(), cells };
}

export function crudCsv(m: CrudMatrix): string {
  const q = (s: string) => (/[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);
  return [['Program', ...m.files].map(q).join(','), ...m.programs.map(p => [p, ...m.files.map(f => m.cells[p]?.[f] ?? '')].map(q).join(','))].join('\n') + '\n';
}

const md = (s: string) => s.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const id = (s: string) => s.replace(/[^A-Za-z0-9_]/g, '_');

/** A Markdown document of a library: what is in it, the files with their columns, what each program uses, a diagram. */
export function libraryMarkdown(lib: string, system: string, objects: DocObject[], columns: DocColumn[], refs: PgmRef[], when = new Date()): string {
  const out: string[] = [`# Library ${lib}`, '', `_${system}, generated by Vanthrex for IBM i on ${when.toISOString().slice(0, 10)}._`, ''];
  const byType = new Map<string, DocObject[]>();
  for (const o of objects) { (byType.get(o.type) ?? byType.set(o.type, []).get(o.type)!).push(o); }
  out.push('## Contents', '', '| Type | Objects |', '|---|---|', ...[...byType].sort().map(([t, l]) => `| ${t} | ${l.length} |`), '');
  const programs = objects.filter(o => o.type === '*PGM' || o.type === '*SRVPGM');
  const files = objects.filter(o => o.type === '*FILE');
  const usesOf = (name: string) => refs.filter(r => r.pgm === name && r.refName);
  if (programs.length) {
    out.push('## Programs', '');
    for (const p of programs) {
      out.push(`### ${p.name} (${p.type.slice(1)}${p.attribute ? ', ' + p.attribute : ''})`, '', md(p.text) || '_No description._', '');
      const u = usesOf(p.name);
      const fl = u.filter(r => r.refType === '*FILE'); const pg = u.filter(r => r.refType === '*PGM' || r.refType === '*SRVPGM'); const other = u.filter(r => !['*FILE', '*PGM', '*SRVPGM'].includes(r.refType));
      if (fl.length) { out.push(`- **Files:** ${fl.map(r => `${r.refName} (${crud(r.usage) || 'used'})`).join(', ')}`); }
      if (pg.length) { out.push(`- **Calls / binds:** ${pg.map(r => `${r.refName} ${r.refType.slice(1)}`).join(', ')}`); }
      if (other.length) { out.push(`- **Other objects:** ${other.map(r => `${r.refName} ${r.refType.slice(1)}`).join(', ')}`); }
      if (p.lastUsed) { out.push(`- **Last used:** ${p.lastUsed}`); }
      out.push('');
    }
  }
  if (files.length) {
    out.push('## Files', '');
    for (const f of files) {
      out.push(`### ${f.name} (${f.attribute || 'FILE'})`, '', md(f.text) || '_No description._', '');
      const cols = columns.filter(c => c.file === f.name);
      if (cols.length) {
        out.push('| Column | Type | Description |', '|---|---|---|', ...cols.map(c => `| ${c.name} | ${c.type}${c.length ? `(${c.length}${c.scale ? ',' + c.scale : ''})` : ''} | ${md(c.text)} |`), '');
      }
      const users = refs.filter(r => r.refType === '*FILE' && r.refName === f.name);
      if (users.length) { out.push(`Used by: ${[...new Set(users.map(r => `${r.pgm} (${crud(r.usage) || 'used'})`))].join(', ')}`, ''); }
    }
  }
  const m = crudMatrix(refs.filter(r => programs.some(p => p.name === r.pgm)));
  if (m.programs.length && m.files.length && m.files.length <= 40) {
    out.push('## CRUD matrix', '', 'C = creates (writes), R = reads, UD = updates or deletes, ? = unspecified.', '',
      `| Program | ${m.files.join(' | ')} |`, `|---|${m.files.map(() => ':-:').join('|')}|`, ...m.programs.map(p => `| ${p.split('/').pop()} | ${m.files.map(f => m.cells[p][f] ?? '').join(' | ')} |`), '');
  }
  const edges = refs.filter(r => programs.some(p => p.name === r.pgm) && ['*FILE', '*PGM', '*SRVPGM'].includes(r.refType)).slice(0, 120);
  if (edges.length) {
    out.push('## Diagram', '', '```mermaid', 'flowchart LR');
    const nodes = new Set<string>();
    for (const e of edges) {
      const a = id(e.pgm); const b = id(`${e.refName}_${e.refType.slice(1)}`);
      if (!nodes.has(a)) { nodes.add(a); out.push(`  ${a}[${e.pgm}]`); }
      if (!nodes.has(b)) { nodes.add(b); out.push(e.refType === '*FILE' ? `  ${b}[(${e.refName})]` : `  ${b}[${e.refName}]`); }
      out.push(`  ${a} -->${e.refType === '*FILE' && crud(e.usage) ? `|${crud(e.usage)}|` : ''} ${b}`);
    }
    out.push('```', '');
  }
  const others = objects.filter(o => !['*PGM', '*SRVPGM', '*FILE'].includes(o.type));
  if (others.length) { out.push('## Other objects', '', '| Name | Type | Description |', '|---|---|---|', ...others.map(o => `| ${o.name} | ${o.type} | ${md(o.text)} |`), ''); }
  return out.join('\n').replace(/\n{3,}/g, '\n\n');
}
