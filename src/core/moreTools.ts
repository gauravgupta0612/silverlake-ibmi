import { isValidSystemName } from './util';

// ---------------------------------------------------------------- RPG code from a table

export interface TableColumn { name: string; system: string; type: string; length: number; scale: number; nullable: boolean; text?: string }

/** RPG free-form type for a Db2 column. */
export function rpgType(c: TableColumn): string {
  const t = c.type.toUpperCase();
  if (/^(CHAR|CHARACTER)$/.test(t)) { return `char(${c.length})`; }
  if (/VARCHAR/.test(t)) { return `varchar(${c.length})`; }
  if (/^DECIMAL$/.test(t)) { return `packed(${c.length}:${c.scale})`; }
  if (/^NUMERIC$/.test(t)) { return `zoned(${c.length}:${c.scale})`; }
  if (t === 'SMALLINT') { return 'int(5)'; }
  if (t === 'INTEGER') { return 'int(10)'; }
  if (t === 'BIGINT') { return 'int(20)'; }
  if (t === 'DATE') { return 'date(*iso)'; }
  if (t === 'TIME') { return 'time(*iso)'; }
  if (t === 'TIMESTMP' || t === 'TIMESTAMP') { return 'timestamp'; }
  if (t === 'DOUBLE' || t === 'FLOAT') { return 'float(8)'; }
  if (t === 'REAL') { return 'float(4)'; }
  if (/^GRAPHIC$/.test(t)) { return `graph(${c.length})`; }
  if (/VARGRAPHIC|VARG/.test(t)) { return `vargraph(${c.length})`; }
  if (/CLOB|DBCLOB/.test(t)) { return 'sqltype(clob:1000000)'; }
  if (/BLOB/.test(t)) { return 'sqltype(blob:1000000)'; }
  if (/DECFLOAT/.test(t)) { return 'packed(31:10)'; }
  return `char(${c.length || 1})`;
}

const cap = (s: string) => s.toLowerCase().replace(/(^|_)(\w)/g, (_, a, b) => b.toUpperCase());

/** A complete RPG free-form snippet to read and write a table with embedded SQL. */
export function rpgForTable(lib: string, table: string, cols: TableColumn[], keys: string[]): string {
  if (!cols.length) { throw new Error('The table has no columns.'); }
  const ds = `${table.toLowerCase()}_t`;
  const k = keys.length ? cols.filter(c => keys.includes(c.name)) : [cols[0]];
  const rest = cols.filter(c => !k.includes(c));
  const id = (c: TableColumn) => c.system.toLowerCase();
  const pad = Math.max(...cols.map(c => id(c).length)) + 2;
  const out: string[] = [
    `// ---- ${lib}/${table}: generated by Vanthrex for IBM i. Review before use. ----`,
    `// Needs: ctl-opt with an SQL precompile (SQLRPGLE source type).`,
    '',
    `// Row of ${table}`,
    `dcl-ds ${ds} qualified template;`,
    ...cols.map(c => `  ${id(c).padEnd(pad)}${rpgType(c)};${c.text ? ` // ${c.text}` : ''}`),
    'end-ds;',
    '',
    `// Or, equivalently, from the file itself:`,
    `// dcl-ds ${table.toLowerCase()}_rec extname('${lib}/${table}') qualified end-ds;`,
    '',
    `// Read one row by key. Returns *on when found.`,
    `dcl-proc get${cap(table)} export;`,
    `  dcl-pi *n ind;`,
    ...k.map(c => `    ${id(c).padEnd(pad)}${rpgType(c)} const;`),
    `    row likeds(${ds});`,
    '  end-pi;',
    `  exec sql select ${cols.map(c => `"${c.name}"`).join(', ')}`,
    `             into :row`,
    `             from ${lib}/${table}`,
    `            where ${k.map(c => `"${c.name}" = :${id(c)}`).join(' and ')};`,
    `  return sqlcode = 0;`,
    'end-proc;',
    '',
    `// Add a row. Returns the SQLCODE (0 = OK, -803 = duplicate key).`,
    `dcl-proc add${cap(table)} export;`,
    `  dcl-pi *n int(10);`,
    `    row likeds(${ds}) const;`,
    '  end-pi;',
    `  exec sql insert into ${lib}/${table} (${cols.map(c => `"${c.name}"`).join(', ')})`,
    `             values(${cols.map(c => `:row.${id(c)}`).join(', ')});`,
    '  return sqlcode;',
    'end-proc;',
    '',
    `// Change a row by key. Returns the SQLCODE (100 = not found).`,
    `dcl-proc update${cap(table)} export;`,
    `  dcl-pi *n int(10);`,
    `    row likeds(${ds}) const;`,
    '  end-pi;',
    ...(rest.length ? [`  exec sql update ${lib}/${table}`, `             set ${rest.map(c => `"${c.name}" = :row.${id(c)}`).join(',\n                 ')}`,
      `           where ${k.map(c => `"${c.name}" = :row.${id(c)}`).join(' and ')};`] : ['  // Every column is part of the key: nothing to update.']),
    '  return sqlcode;',
    'end-proc;',
    '',
    `// Delete a row by key. Returns the SQLCODE (100 = not found).`,
    `dcl-proc delete${cap(table)} export;`,
    `  dcl-pi *n int(10);`,
    ...k.map(c => `    ${id(c).padEnd(pad)}${rpgType(c)} const;`),
    '  end-pi;',
    `  exec sql delete from ${lib}/${table} where ${k.map(c => `"${c.name}" = :${id(c)}`).join(' and ')};`,
    '  return sqlcode;',
    'end-proc;',
    '',
    `// Read all rows in key order.`,
    `dcl-proc list${cap(table)} export;`,
    `  dcl-s row likeds(${ds});`,
    `  exec sql declare c_${table.toLowerCase()} cursor for`,
    `           select ${cols.map(c => `"${c.name}"`).join(', ')}`,
    `             from ${lib}/${table}`,
    `            order by ${k.map(c => `"${c.name}"`).join(', ')};`,
    `  exec sql open c_${table.toLowerCase()};`,
    `  dow *on;`,
    `    exec sql fetch next from c_${table.toLowerCase()} into :row;`,
    `    if sqlcode <> 0;`,
    `      leave;`,
    `    endif;`,
    `    // … use row.${id(cols[0])} …`,
    `  enddo;`,
    `  exec sql close c_${table.toLowerCase()};`,
    'end-proc;',
  ];
  return out.join('\n') + '\n';
}

// ---------------------------------------------------------------- SQL formatter

const KEYWORDS = new Set(('SELECT FROM WHERE AND OR NOT IN IS NULL AS ON JOIN INNER LEFT RIGHT FULL OUTER CROSS EXCEPTION GROUP BY ORDER HAVING UNION ALL DISTINCT ' +
  'INSERT INTO VALUES UPDATE SET DELETE CREATE OR REPLACE TABLE VIEW INDEX ALTER DROP ADD COLUMN PRIMARY KEY FOREIGN REFERENCES WITH CASE WHEN THEN ELSE END ' +
  'FETCH FIRST NEXT ROWS ROW ONLY OFFSET LIMIT ASC DESC BETWEEN LIKE EXISTS ANY SOME CAST COALESCE CURRENT DATE TIME TIMESTAMP DEFAULT CALL DECLARE CURSOR FOR ' +
  'OPEN CLOSE COMMIT ROLLBACK LATERAL TABLE MERGE USING MATCHED INTERSECT EXCEPT LABEL COMMENT GRANT REVOKE TO NC CS RR RS UR DISTINCT').split(' '));
const CLAUSES = /^(SELECT|FROM|WHERE|GROUP BY|ORDER BY|HAVING|UNION ALL|UNION|INTERSECT|EXCEPT|FETCH FIRST|OFFSET|LIMIT|VALUES|SET|INSERT INTO|UPDATE|DELETE FROM|WITH|(LEFT |RIGHT |FULL |INNER |CROSS |EXCEPTION |LEFT OUTER |RIGHT OUTER |FULL OUTER )?JOIN|ON|MERGE INTO|USING|WHEN MATCHED|WHEN NOT MATCHED)$/;

interface Tok { t: 'word' | 'str' | 'num' | 'punct' | 'comment' | 'space'; v: string }

function tokenize(sql: string): Tok[] {
  const out: Tok[] = []; let i = 0;
  while (i < sql.length) {
    const c = sql[i];
    if (/\s/.test(c)) { let j = i; while (j < sql.length && /\s/.test(sql[j])) { j++; } out.push({ t: 'space', v: sql.slice(i, j) }); i = j; continue; }
    if (c === '-' && sql[i + 1] === '-') { const j = sql.indexOf('\n', i); const e = j < 0 ? sql.length : j; out.push({ t: 'comment', v: sql.slice(i, e) }); i = e; continue; }
    if (c === '/' && sql[i + 1] === '*') { const j = sql.indexOf('*/', i + 2); const e = j < 0 ? sql.length : j + 2; out.push({ t: 'comment', v: sql.slice(i, e) }); i = e; continue; }
    if (c === "'" || c === '"') { let j = i + 1; while (j < sql.length) { if (sql[j] === c) { if (sql[j + 1] === c) { j += 2; continue; } break; } j++; } out.push({ t: 'str', v: sql.slice(i, j + 1) }); i = j + 1; continue; }
    if (/[A-Za-z_$#@:]/.test(c)) { let j = i + 1; while (j < sql.length && /[\w$#@./*-]/.test(sql[j]) && !(sql[j] === '-' && sql[j + 1] === '-') && !(sql[j] === '*' && !/[/.]/.test(sql[j - 1]))) { j++; } out.push({ t: 'word', v: sql.slice(i, j) }); i = j; continue; }
    if (/\d/.test(c)) { let j = i + 1; while (j < sql.length && /[\d.eE]/.test(sql[j])) { j++; } out.push({ t: 'num', v: sql.slice(i, j) }); i = j; continue; }
    if ((c === '<' || c === '>' || c === '!' || c === '|') && /[=>|]/.test(sql[i + 1] ?? '')) { out.push({ t: 'punct', v: sql.slice(i, i + 2) }); i += 2; continue; }
    out.push({ t: 'punct', v: c }); i++;
  }
  return out;
}

/** Format Db2 for i SQL: keywords upper case, one clause per line, select lists and AND/OR indented. */
export function formatSql(sql: string, indent = '  '): string {
  const toks = tokenize(sql).filter(t => t.t !== 'space');
  const lines: string[] = []; let cur = ''; let depth = 0; let clause = '';
  const stack: { depth: number; clause: string }[] = [];
  const nl = (extra = 0) => { if (cur.trim()) { lines.push(cur.replace(/\s+$/, '')); } cur = indent.repeat(Math.max(0, depth + extra)); };
  const word = (t: Tok) => (t.t === 'word' && KEYWORDS.has(t.v.toUpperCase()) ? t.v.toUpperCase() : t.v);
  for (let i = 0; i < toks.length; i++) {
    const t = toks[i];
    if (t.t === 'comment') { cur = cur.trimEnd() + (cur.trim() ? ' ' : cur) + t.v; if (t.v.startsWith('--')) { nl(); } else { cur += ' '; } continue; }
    if (t.v === ';') { cur = cur.trimEnd() + ';'; nl(); lines.push(''); depth = 0; clause = ''; continue; }
    // Multi-word clauses.
    let w = word(t); let used = 0;
    for (const n of [3, 2]) {
      const phrase = toks.slice(i, i + n).map(word).join(' ');
      if (toks.slice(i, i + n).every(x => x.t === 'word') && CLAUSES.test(phrase)) { w = phrase; used = n - 1; break; }
    }
    if (t.t === 'word' && CLAUSES.test(w)) {
      if (w === 'ON') { nl(1); } else { nl(); }
      cur += w; clause = w; i += used;
      if (/^(SELECT|SET|GROUP BY|ORDER BY)$/.test(w)) { nl(1); }
      else { cur += ' '; }
      continue;
    }
    if (t.t === 'word' && /^(AND|OR)$/.test(w) && /^(WHERE|ON|HAVING|WHEN MATCHED)$/.test(clause) && !stack.some(s => s.depth === depth && s.clause === 'BETWEEN')) {
      const prev = toks[i - 2]; if (prev && word(prev) === 'BETWEEN') { cur = `${cur.trimEnd()} ${w} `; continue; }
      nl(1); cur += `${w} `; continue;
    }
    if (t.v === '(') {
      const next = toks[i + 1];
      if (next && next.t === 'word' && /^(SELECT|WITH)$/i.test(next.v)) { cur += '('; stack.push({ depth, clause }); depth++; continue; }
      cur = cur.replace(/\s+$/, (m) => (/[\w"]$/.test(cur.trimEnd()) && !/\b(IN|AS|VALUES|EXISTS|ON|AND|OR|=)\s*$/i.test(cur) ? '' : m)) + '('; stack.push({ depth: -1, clause }); continue;
    }
    if (t.v === ')') {
      const s = stack.pop();
      if (s && s.depth >= 0) { depth = s.depth; clause = s.clause; nl(); cur += ')'; continue; }
      cur = cur.replace(/\s+$/, '') + ') '; continue;
    }
    if (t.v === ',') {
      cur = cur.replace(/\s+$/, '') + ',';
      if ((stack.length === 0 || stack[stack.length - 1].depth >= 0) && /^(SELECT|SET|GROUP BY|ORDER BY)$/.test(clause)) { nl(1); } else { cur += ' '; }
      continue;
    }
    if (t.v === '.' ) { cur = cur.replace(/\s+$/, '') + '.'; continue; }
    cur += (cur.endsWith('(') || cur.endsWith('.') ? '' : (cur.trim() && !/\s$/.test(cur) ? ' ' : '')) + (t.t === 'word' ? w : t.v) + ' ';
  }
  nl();
  return lines.join('\n').replace(/\n{3,}/g, '\n\n').replace(/[ \t]+$/gm, '').trim() + '\n';
}

// ---------------------------------------------------------------- submit & watch

/** The job a SBMJOB started, from its CPC1221 completion message. */
export function submittedJob(output: string): string | undefined {
  return /Job (\d{6}\/[A-Z0-9$#@_.]{1,10}\/[A-Z0-9$#@_.]{1,10}) submitted/i.exec(output)?.[1]?.toUpperCase();
}

export function sbmjobCommand(command: string, job: string, jobq?: string): string {
  const name = job.trim().toUpperCase();
  if (!isValidSystemName(name)) { throw new Error(`"${job}" is not a valid job name.`); }
  if (!command.trim()) { throw new Error('Enter the command to submit.'); }
  return `SBMJOB CMD(${command.trim()}) JOB(${name})${jobq?.trim() ? ` JOBQ(${jobq.trim().toUpperCase()})` : ''}`;
}

/** Where a submitted job is, from QSYS2.JOB_INFO's JOB_STATUS. */
export function jobPhase(status: string): 'queued' | 'running' | 'ended' | 'unknown' {
  const s = status.toUpperCase().trim();
  if (/^(JOBQ|\*JOBQ)$/.test(s)) { return 'queued'; }
  if (/^(ACTIVE|\*ACTIVE)$/.test(s)) { return 'running'; }
  if (/^(OUTQ|\*OUTQ|ENDED|\*COMPLETE)$/.test(s)) { return 'ended'; }
  return 'unknown';
}

// ---------------------------------------------------------------- search & replace across members

export interface ReplaceOptions { regex: boolean; matchCase: boolean; wholeWord: boolean }

export function buildPattern(find: string, o: ReplaceOptions): RegExp {
  if (!find) { throw new Error('Enter the text to find.'); }
  let src = o.regex ? find : find.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  if (o.wholeWord) { src = `(?<![\\w$#@])${src}(?![\\w$#@])`; }
  try { return new RegExp(src, o.matchCase ? 'g' : 'gi'); } catch (e) { throw new Error(`Invalid regular expression: ${(e as Error).message}`); }
}

/** Replace in each line; returns the new lines and which lines changed. Lines never grow beyond maxLength. */
export function replaceLines(lines: string[], re: RegExp, replacement: string, maxLength = 0): { lines: string[]; changed: number[]; tooLong: number[] } {
  const changed: number[] = []; const tooLong: number[] = [];
  const out = lines.map((l, i) => {
    re.lastIndex = 0;
    if (!re.test(l)) { return l; }
    re.lastIndex = 0;
    const n = l.replace(re, replacement);
    if (maxLength && n.trimEnd().length > maxLength && n.trimEnd().length > l.trimEnd().length) { tooLong.push(i); return l; }
    if (n !== l) { changed.push(i); }
    return n;
  });
  return { lines: out, changed, tooLong };
}

// ---------------------------------------------------------------- library list sets

export interface LibrarySet { name: string; libraries: string[]; currentLibrary?: string }

export function parseLibraryList(input: string): string[] {
  const libs = input.split(/[\s,;]+/).map(x => x.trim().toUpperCase()).filter(Boolean);
  const bad = libs.filter(l => !isValidSystemName(l));
  if (bad.length) { throw new Error(`Not a valid library name: ${bad.join(', ')}`); }
  if (libs.length > 250) { throw new Error('A library list holds at most 250 libraries.'); }
  return [...new Set(libs)];
}
